import { readFile, readdir, writeFile } from 'node:fs/promises';
import { extname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const clientRoot = new URL('./dist/client/', import.meta.url);
const workerPath = new URL('./dist/server/index.js', import.meta.url);
const marker = '// Generated by build-assets.mjs. Edit files in dist/client to update this section.';
const contentTypes = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.png': 'image/png',
  '.webp': 'image/webp',
  '.svg': 'image/svg+xml',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
};

async function collectAssets(directory, prefix, assets) {
  const entries = (await readdir(directory, { withFileTypes: true }))
    .sort((first, second) => first.name.localeCompare(second.name, 'en'));
  for (const file of entries) {
    const filename = encodeURIComponent(file.name);
    const route = `${prefix}/${filename}`;
    if (file.isDirectory()) {
      await collectAssets(new URL(`${filename}/`, directory), route, assets);
      continue;
    }

    const type = contentTypes[extname(file.name).toLowerCase()];
    if (!file.isFile() || !type) throw new Error(`Unsupported client asset ${route}`);
    const bytes = await readFile(new URL(filename, directory));
    assets[route] = [type, bytes.toString('base64')];
  }
}

export async function buildAssets() {
  const assets = {};
  await collectAssets(clientRoot, '', assets);
  if (!assets['/index.html']) throw new Error('The client bundle must contain index.html.');

  const worker = await readFile(workerPath, 'utf8');
  const markerIndex = worker.indexOf(marker);
  if (markerIndex === -1) throw new Error('The Worker is missing the generated asset marker.');

  const output = `${worker.slice(0, markerIndex)}${marker}\nconst EMBEDDED_ASSETS = ${JSON.stringify(assets)};\n`;
  await writeFile(workerPath, output);
  return Object.keys(assets).length;
}

const script = globalThis.process?.argv[1];
if (script && resolve(script) === fileURLToPath(import.meta.url)) {
  console.log(`Embedded ${await buildAssets()} client assets in the Worker.`);
}
